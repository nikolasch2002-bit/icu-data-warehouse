"""Run the analytic queries and snapshot their results in RESULTS.md.

Each NN_*.sql file starts with a comment block: the first line is the
title, the rest explains what the result means clinically. That text and
the result table go into RESULTS.md.

Usage:
    python -m analytics.run           # rewrite analytics/RESULTS.md
    python -m analytics.run --check   # fail if a query errors or RESULTS.md is stale
"""

import argparse
import sys
from decimal import Decimal
from pathlib import Path

import psycopg

from loader.load_raw import database_url

ANALYTICS_DIR = Path(__file__).resolve().parent
RESULTS_PATH = ANALYTICS_DIR / "RESULTS.md"

INTRO = """# Analytic query results

Results of the queries in this folder against the MIMIC-IV Clinical
Database Demo v2.2 (100 patients). Generated by `python -m analytics.run`;
CI fails if this file no longer matches the queries.
"""


def query_files() -> list[Path]:
    return sorted(ANALYTICS_DIR.glob("[0-9][0-9]_*.sql"))


def read_header(sql_text: str) -> tuple[str, list[str]]:
    """The title and the description paragraphs from the leading comments."""
    lines = []
    for line in sql_text.splitlines():
        if not line.startswith("--"):
            break
        lines.append(line.removeprefix("--").strip())

    title, *body = lines
    paragraphs, current = [], []
    for line in body:
        if line:
            current.append(line)
        elif current:
            paragraphs.append(" ".join(current))
            current = []
    if current:
        paragraphs.append(" ".join(current))
    return title, paragraphs


def format_value(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, Decimal):
        return format(value, "f")
    return str(value)


def to_markdown(columns: list[str], rows: list[tuple]) -> str:
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(format_value(v) for v in row) + " |")
    return "\n".join(lines)


def render(conn: psycopg.Connection) -> str:
    sections = [INTRO]
    for path in query_files():
        sql_text = path.read_text(encoding="utf-8")
        title, paragraphs = read_header(sql_text)
        with conn.cursor() as cur:
            cur.execute(sql_text)
            columns = [c.name for c in cur.description]
            rows = cur.fetchall()
        sections.append(
            "\n\n".join(
                [f"## {title}", *paragraphs, f"[SQL]({path.name})"]
                + [to_markdown(columns, rows)]
            )
            + "\n"
        )
    return "\n".join(sections)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail if RESULTS.md differs from a fresh run",
    )
    args = parser.parse_args()

    with psycopg.connect(database_url()) as conn:
        results = render(conn)

    if args.check:
        # Git on Windows may check the file out with \r\n line endings.
        current = RESULTS_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != results:
            sys.exit(
                "analytics/RESULTS.md is out of date: "
                "run python -m analytics.run and commit it."
            )
        print(f"{len(query_files())} queries ran; RESULTS.md is up to date.")
    else:
        RESULTS_PATH.write_text(results, encoding="utf-8", newline="\n")
        print(f"Wrote {RESULTS_PATH.name} ({len(query_files())} queries).")


if __name__ == "__main__":
    main()
